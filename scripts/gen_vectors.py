#!/usr/bin/env python3
"""Generate Dahlias/VectorData.lean from the BIP 459 test vector CSV files.

Usage: python3 scripts/gen_vectors.py <path to bip-0459/vectors> > Dahlias/VectorData.lean

Every row becomes the list of its CSV fields, without the header.
"""

import csv
import json
import sys
from pathlib import Path

FILES = [
    ("nonceGenRows", "test_vectors_nonce_gen.csv", 7),
    ("nonceAggRows", "test_vectors_nonce_agg.csv", 5),
    ("signRows", "test_vectors_sign.csv", 8),
    ("signErrorRows", "test_vectors_sign_error.csv", 9),
    ("partialSigVerifyRows", "test_vectors_partial_sig_verify.csv", 8),
    ("verifyRows", "test_vectors_verify.csv", 6),
    ("tweakRows", "test_vectors_tweak.csv", 8),
]


def main():
    d = Path(sys.argv[1])
    out = [
        "/-! Generated by `scripts/gen_vectors.py` from `bip-0459/vectors/*.csv`. Do not edit. -/",
        "",
        "namespace Dahlias.Vectors",
        "",
    ]
    for name, filename, width in FILES:
        with open(d / filename, newline="", encoding="utf-8") as f:
            rows = list(csv.reader(f))[1:]
        assert rows and all(len(r) == width for r in rows), filename
        out.append(f"def {name} : List (List String) := [")
        out.append(",\n".join(
            "  [" + ",\n   ".join(json.dumps(c, ensure_ascii=True) for c in r) + "]" for r in rows) + "]")
        out.append("")
    out.append("end Dahlias.Vectors")
    print("\n".join(out))


if __name__ == "__main__":
    main()
